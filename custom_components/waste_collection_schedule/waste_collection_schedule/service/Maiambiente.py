# ------------------------------------------------------------- PDF -> images
def _chunk(tag, data):
    return (
        struct.pack(">I", len(data))
        + tag
        + data
        + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    )


def _wrap_png(idat, w, h):
    ihdr = struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)  # 8 bpc, type 2 = RGB
    return (
        b"\x89PNG\r\n\x1a\n"
        + _chunk(b"IHDR", ihdr)
        + _chunk(b"IDAT", idat)
        + _chunk(b"IEND", b"")
    )


def imagens_do_pdf(pdf_bytes):
    """RGB images in the PDF (only /FlateDecode + /Predictor 15 + DeviceRGB)."""
    for m in _IMG_RE.finditer(pdf_bytes):
        # keep the dictionary scan inside THIS object: picking up the previous
        # object's /Length truncates the stream and the image comes out corrupt
        ini = pdf_bytes.rfind(b" obj", 0, m.start())
        head = pdf_bytes[ini if ini >= 0 else max(0, m.start() - 600) : m.end()]

        def val(key, default=None, head=head):
            g = re.search(rf"/{key}\s+(\d+)".encode(), head)
            return int(g.group(1)) if g else default

        w, h = val("Width"), val("Height")
        if not w or not h or val("BitsPerComponent", 8) != 8:
            continue
        if (
            b"/FlateDecode" not in head
            or b"/DeviceRGB" not in head
            or re.search(rb"/Predictor\s+15", head) is None
        ):
            continue
        length = val("Length")
        if length:
            raw = pdf_bytes[m.end() : m.end() + length]
        else:
            raw = pdf_bytes[m.end() : pdf_bytes.find(b"endstream", m.end())]
        try:
            img = Image.open(io.BytesIO(_wrap_png(raw, w, h)))
            # the PNG we just built is colour type 2, so it decodes straight to
            # RGB. Calling convert("RGB") anyway would hand back a full copy of
            # a 25 megapixel image, which on a 2 GB Home Assistant box is the
            # difference between working and being OOM-killed.
            yield img if img.mode == "RGB" else img.convert("RGB")
        except Exception:
            continue


def texto_do_pdf(pdf_bytes):
    """Text of the content streams - enough for the PNG name and the circuits."""
    out = []
    for m in re.finditer(rb"stream\r?\n", pdf_bytes):
        fim = pdf_bytes.find(b"endstream", m.end())
        try:
            data = zlib.decompress(pdf_bytes[m.end() : fim])
        except Exception:
            continue
        if b"Tj" not in data and b"TJ" not in data:
            continue
        for t in re.finditer(rb"\((?:\\.|[^\\()])*\)", data):
            s = re.sub(rb"\\([()\\])", rb"\1", t.group(0)[1:-1])
            out.append(s.decode("latin-1"))
    return "\n".join(out)


def assinatura(pdf_bytes):
    """Identify the calendar.

    `png` is the name of the embedded bitmap (e.g. 20502edbd9f2_2026.png).
    Because the calendar belongs to the circuit, that name works as a cache
    key: if it has not changed, neither has the calendar.
    """
    txt = texto_do_pdf(pdf_bytes)
    png = re.search(r"([0-9a-f]{6,}_\d{4}\.png)", txt)
    circ = re.findall(r"[A-Z]{1,2}\d+\.\d+_\d{4}", txt)
    morada = re.search(r"^(.+?,\s*\d.*)$", txt, re.M)
    return {
        "png": png.group(1) if png else None,
        "circuitos": sorted(set(circ)) or None,
        "morada": morada.group(1).strip() if morada else None,
    }


# ------------------------------------------------------------ reading the grid
def classificar(cor):
    """Name of the stream whose colour is within TOL (L1 distance), or None."""
    v = _COLOUR_CACHE.get(cor)
    if v is None:
        melhor, d = None, TOL
        for nome, c in PALETTE.items():
            dd = abs(cor[0] - c[0]) + abs(cor[1] - c[1]) + abs(cor[2] - c[2])
            if dd < d:
                melhor, d = nome, dd
        v = _COLOUR_CACHE[cor] = melhor
    return v


def _mascara(im):
    """An 'L' image at 255 wherever the pixel is a palette colour."""
    w, h = im.size
    acc = Image.new("L", (w, h), 0)
    for c in PALETTE.values():
        r, g, b = ImageChops.difference(im, Image.new("RGB", (w, h), c)).split()
        s = ImageChops.add(ImageChops.add(r, g), b)  # L1, saturates at 255
        acc = ImageChops.lighter(acc, s.point(lambda v: 255 if v < TOL else 0))
    return acc


def _componentes(mask, margem_esq):
    """Connected components, by byte runs (regex in C) + union-find."""
    w, h = mask.size
    data = mask.tobytes()
    pai = [0]

    def raiz(x):
        while pai[x] != x:
            pai[x] = pai[pai[x]]
            x = pai[x]
        return x

    def unir(a, b):
        ra, rb = raiz(a), raiz(b)
        if ra != rb:
            pai[max(ra, rb)] = min(ra, rb)

    corrida = re.compile(b"\xff+")
    ant, caixas = [], {}
    for y in range(h):
        linha = data[y * w : (y + 1) * w]
        atual = []
        for m in corrida.finditer(linha, margem_esq):
            x0, x1 = m.start(), m.end() - 1
            lbl = None
            for px0, px1, plbl in ant:
                if px1 < x0:
                    continue
                if px0 > x1:
                    break
                if lbl is None:
                    lbl = plbl
                else:
                    unir(lbl, plbl)
            if lbl is None:
                lbl = len(pai)
                pai.append(lbl)
            atual.append((x0, x1, lbl))
            cx = caixas.get(lbl)
            if cx is None:
                caixas[lbl] = [x0, y, x1, y]
            else:
                cx[0] = min(cx[0], x0)
                cx[2] = max(cx[2], x1)
                cx[3] = y
        ant = atual

    final = {}
    for lbl, (x0, y0, x1, y1) in caixas.items():
        r = raiz(lbl)
        f = final.get(r)
        if f is None:
            final[r] = [x0, y0, x1, y1]
        else:
            f[0] = min(f[0], x0)
            f[1] = min(f[1], y0)
            f[2] = max(f[2], x1)
            f[3] = max(f[3], y1)
    return list(final.values())


def _agrupar(vals, tol):
    vals = sorted(vals)
    g = [[vals[0]]]
    for v in vals[1:]:
        if v - g[-1][-1] <= tol:
            g[-1].append(v)
        else:
            g.append([v])
    return [sum(x) / len(x) for x in g]


def _mediana(v):
    v = sorted(v)
    return v[len(v) // 2]


def _barras_dos_meses(im):
    """Bounding boxes of the 12 dark-green bars carrying the month names.

    They anchor the grid: they say which band (block row) and which group
    (block column) each month sits in, without depending on circles being
    present. That keeps the alignment intact for circuits that do not collect
    on some weekday.
    """
    w, h = im.size
    r, g, b = ImageChops.difference(im, Image.new("RGB", (w, h), TEAL)).split()
    mask = ImageChops.add(ImageChops.add(r, g), b).point(lambda v: 255 if v < 40 else 0)
    barras = []
    for x0, y0, x1, y1 in _componentes(mask, 0):
        bw, bh = x1 - x0 + 1, y1 - y0 + 1
        if bh < h * 0.2 or bh > h * 0.45 or bw > bh * 0.25 or bw < 15:
            continue
        barras.append((x0, y0, x1, y1))
    if len(barras) != 12:
        raise CalendarioError(f"expected 12 month bars, found {len(barras)}")
    bandas = sorted({b[1] for b in barras})
    grupos = sorted({b[0] for b in barras})
    bandas = _agrupar(bandas, 40)
    grupos = _agrupar(grupos, 40)
    if len(bandas) != 3 or len(grupos) != 4:
        raise CalendarioError(
            f"month bars in {len(bandas)} bands x {len(grupos)} groups"
        )
    out = {}
    for x0, y0, x1, y1 in barras:
        br = min(range(3), key=lambda i: abs(bandas[i] - y0))
        bc = min(range(4), key=lambda i: abs(grupos[i] - x0))
        out[(br, bc)] = (x0, y0, x1, y1)
    if len(out) != 12:
        raise CalendarioError("overlapping month bars")
    return out


def _encaixar(valor, candidatos, tol):
    """Snap `valor` to the nearest candidate, if it is closer than `tol`."""
    if not candidatos:
        return valor
    melhor = min(candidatos, key=lambda c: abs(c - valor))
    return melhor if abs(melhor - valor) <= tol else valor


def ler_calendario(pdf_bytes, year):
    """Return ({datetime.date: [streams]}, [warnings]).

    Raises CalendarioError when the grid stops being recognisable - the signal
    that Maiambiente has changed the calendar's design.
    """
    im, melhor = None, -1
    for cand in imagens_do_pdf(pdf_bytes):
        # score on a subsample: the fill colours are flat, so nearest-neighbour
        # keeps them exact, and this avoids walking 25 million pixels per
        # candidate just to decide which image is the calendar
        amostra_im = cand.resize(
            (cand.width // 8 or 1, cand.height // 8 or 1), Image.NEAREST
        )
        cores = amostra_im.getcolors(1 << 16) or []
        score = sum(n for n, c in cores if classificar(c))
        del amostra_im, cores
        if score > melhor:
            im, melhor = cand, score
        else:
            del cand
    if im is None:
        raise CalendarioError("could not find the calendar image in the PDF")

    w, h = im.size
    margem = int(w * 0.05)  # the legend column, on the left
    circulos = []
    for x0, y0, x1, y1 in _componentes(_mascara(im), margem):
        ww, hh = x1 - x0 + 1, y1 - y0 + 1
        if ww < 25 or hh < 25 or abs(ww - hh) > 10:
            continue
        circulos.append(((x0 + x1) / 2.0, (y0 + y1) / 2.0))
    if len(circulos) < 100:
        raise CalendarioError(
            f"only detected {len(circulos)} circles - has the format changed?"
        )

    barras = _barras_dos_meses(im)
    altura_barra = _mediana([b[3] - b[1] + 1 for b in barras.values()])
    # the bar spans 7 day rows with an equal margin above and below
    passo_barra = altura_barra * 0.1435

    linhas = _agrupar([c[1] for c in circulos], 15)
    colunas = _agrupar([c[0] for c in circulos], 15)

    def passo(vals, referencia):
        difs = [
            d
            for d in (vals[i + 1] - vals[i] for i in range(len(vals) - 1))
            if referencia * 0.85 < d < referencia * 1.15
        ]
        return _mediana(difs) if difs else referencia

    row_pitch = passo(linhas, passo_barra)
    col_pitch = passo(colunas, passo_barra)

    rad = int(col_pitch * 0.30)  # square inscribed in the circle
    area = (2 * rad + 1) ** 2

    def amostra(cx, cy):
        """Streams present in the cell (each with >=15% of the pixels), or []."""
        if not (rad <= cx < w - rad and rad <= cy < h - rad):
            return []
        cnt = Counter()
        for n, cor in (
            im.crop((cx - rad, cy - rad, cx + rad + 1, cy + rad + 1)).getcolors(1 << 16)
            or []
        ):
            f = classificar(cor)
            if f:
                cnt[f] += n
        tot = sum(cnt.values())
        if tot < area * 0.25:  # blank cell: no collection
            return []
        return [k for k, v in cnt.most_common() if v / tot >= 0.15]

    eventos, avisos = {}, []
    for (br, bc), (bx0, by0, _bx1, by1) in sorted(barras.items()):
        month = MONTH_GRID[br][bc]
        # row 0 (Monday) and week column 0, anchored on the month bar and then
        # snapped onto the circles that actually exist
        y_seg = _encaixar(
            by0 + ((by1 - by0 + 1) - 6 * row_pitch) / 2.0, linhas, row_pitch * 0.4
        )
        x_sem0 = _encaixar(bx0 - col_pitch, colunas, col_pitch * 0.4)

        primeiro = dt.date(year, month, 1)
        segunda = primeiro - dt.timedelta(days=primeiro.weekday())
        for row in range(7):  # Mon..Sun
            cy = round(y_seg + row * row_pitch)
            for semana in range(6):  # at most 6 weeks
                fluxos = amostra(round(x_sem0 - semana * col_pitch), cy)
                if not fluxos:
                    continue
                d = segunda + dt.timedelta(days=7 * semana + row)
                if d not in eventos or len(fluxos) > len(eventos[d]):
                    eventos[d] = fluxos
    if not eventos:
        raise CalendarioError("extracted no collection at all from the calendar")
    return eventos, avisos


# -------------------------------------------------------------------- export
def para_ics(eventos, nome="Recolha de resíduos (Maiambiente)", hora="14:00"):
    """iCalendar with one event per stream per day."""
    hh, mm = (int(x) for x in hora.split(":"))
    agora = dt.datetime.now(dt.timezone.utc)
    linhas = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//ha-maiambiente//PT",
        "CALSCALE:GREGORIAN",
        f"X-WR-CALNAME:{nome}",
        "X-WR-TIMEZONE:Europe/Lisbon",
    ]
    for d in sorted(eventos):
        for f in eventos[d]:
            cab = [
                "BEGIN:VEVENT",
                f"UID:{d:%Y%m%d}-{f}@maiambiente",
                f"DTSTAMP:{agora:%Y%m%dT%H%M%SZ}",
            ]
            if f == "sem_recolha":
                linhas += [
                    *cab,
                    f"DTSTART;VALUE=DATE:{d:%Y%m%d}",
                    f"DTEND;VALUE=DATE:{d + dt.timedelta(days=1):%Y%m%d}",
                    f"SUMMARY:{LABELS[f]}",
                    "END:VEVENT",
                ]
            else:
                s = dt.datetime.combine(d, dt.time(hh, mm))
                linhas += [
                    *cab,
                    f"DTSTART;TZID=Europe/Lisbon:{s:%Y%m%dT%H%M%S}",
                    f"DTEND;TZID=Europe/Lisbon:{s + dt.timedelta(hours=1):%Y%m%dT%H%M%S}",
                    f"SUMMARY:{LABELS[f]}",
                    f"CATEGORIES:{f}",
                    "END:VEVENT",
                ]
    linhas.append("END:VCALENDAR")
    return "\r\n".join(linhas) + "\r\n"
