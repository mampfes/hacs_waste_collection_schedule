# What to tell the user when even the pinned intermediate no longer helps.
CHAIN_HINT = (
    "TLS verification against servicos.maiambiente.pt failed. Their server "
    "sends an incomplete certificate chain and the intermediate pinned in "
    "lib/tls.py no longer bridges it — it most likely needs refreshing. See "
    "the docstring of that module for how."
)


def tls_context() -> ssl.SSLContext:
    """Default verification, plus the intermediate the server forgets to send."""
    ctx = ssl.create_default_context()
    ctx.load_verify_locations(cadata=INTERMEDIATE_PEM)
    return ctx


def tls_session():
    """A `requests.Session` using :func:`tls_context`, or None without requests."""
    try:
        import requests
        import urllib3
    except ImportError:  # pragma: no cover - urllib fallback path
        return None

    class _Adapter(requests.adapters.HTTPAdapter):
        """Transport adapter that carries our SSL context."""

        def __init__(self, ssl_context, **kwargs):
            self._ssl_context = ssl_context
            super().__init__(**kwargs)

        def init_poolmanager(self, connections, maxsize, block=False, **kwargs):
            self.poolmanager = urllib3.poolmanager.PoolManager(
                num_pools=connections,
                maxsize=maxsize,
                block=block,
                ssl_context=self._ssl_context,
                **kwargs,
            )

    sess = requests.Session()
    sess.mount("https://", _Adapter(tls_context()))
    return sess


# ------------------------------ consulta.py
class MaiambienteError(Exception):
    """Something went wrong talking to Maiambiente."""


class Cliente:
    """Throttled session. Uses requests when available, urllib otherwise."""

    def __init__(self, year, throttle=THROTTLE, timeout=60):
        self.year = year
        self.throttle = throttle
        self.timeout = timeout
        self._last = 0.0
        self._sess = tls_session()

    # ------------------------------------------------------------------ HTTP
    def _wait(self):
        delta = time.monotonic() - self._last
        if delta < self.throttle:
            time.sleep(self.throttle - delta)
        self._last = time.monotonic()

    def _request(self, url, data=None, params=None):
        self._wait()
        if self._sess is not None:
            import requests

            try:
                response = (
                    self._sess.post(url, data=data, timeout=self.timeout)
                    if data
                    else self._sess.get(url, params=params, timeout=self.timeout)
                )
            except requests.exceptions.SSLError as err:
                raise MaiambienteError(CHAIN_HINT) from err
            if response.status_code == 403:
                raise MaiambienteError(
                    "403 from the server - too many requests in a row; "
                    "raise the throttle"
                )
            response.raise_for_status()
            return response.content, response.headers.get("content-type", "")

        # fallback without requests
        import ssl
        import urllib.parse
        import urllib.request

        if params:
            url = url + "?" + urllib.parse.urlencode(params)
        body = urllib.parse.urlencode(data).encode() if data else None
        request = urllib.request.Request(url, data=body, headers={"User-Agent": UA})
        try:
            with urllib.request.urlopen(
                request, timeout=self.timeout, context=tls_context()
            ) as response:
                return response.read(), response.headers.get("content-type", "")
        except ssl.SSLCertVerificationError as err:
            raise MaiambienteError(CHAIN_HINT) from err

    def _ajax(self, data):
        raw, _ = self._request(
            BASE.format(year=self.year) + "/ajax_refresh.php", data=data
        )
        return raw.decode("utf-8", "replace")

    # ------------------------------------------------------------------- API
    def arruamentos(self, keyword):
        """Streets whose name contains `keyword` (without "de"/"da"/"das")."""
        html = self._ajax(
            {
                "keyword": keyword,
                "type": f"arruamento{self.year}",
                "freguesia": "",
                "tipoarruamento": "",
            }
        )
        return [m.group(1) for m in re.finditer(r"set_item\d*\([^)]*'([^']*)'\)", html)]

    def numeros(self, arruamento):
        """House numbers of the street, each with its own idcal/idunico."""
        html = self._ajax(
            {
                "keyword": arruamento,
                "type": f"numeropolicia{self.year}",
                "freguesia": "",
                "tipoarruamento": "",
            }
        )
        out = []
        for m in re.finditer(r'href="([^"]*)"[^>]*>([^<]*)<', html):
            qs = dict(re.findall(r"([^?=&]+)=([^&]*)", m.group(1)))
            if not qs.get("idcal"):
                continue
            out.append(
                {
                    "numero": m.group(2).strip(),
                    "idcal": qs["idcal"],
                    "idunico": qs.get("idunico", ""),
                }
            )
        return out

    def circuitos(self, arruamento, numero):
        """Circuit codes of the address (A=food waste, E=packaging, ...)."""
        html = self._ajax(
            {
                "keyword": arruamento,
                "type": "circuito",
                "numeropolicia": numero,
                "freguesia": "",
                "tipoarruamento": "",
            }
        )
        m = re.search(r"set_circuito\('([^']*)'", html)
        return [c.strip() for c in m.group(1).split(",")] if m else []

    def pdf(self, idcal, idunico, arruamento, numero):
        """The address's yearly calendar PDF."""
        raw, ctype = self._request(
            BASE.format(year=self.year) + f"/cal{self.year}.php",
            params={
                "idcal": idcal,
                "idunico": idunico,
                "type": f"logcircuito{self.year}",
                "morada": arruamento,
                "numeropolicia": numero,
            },
        )
        if "pdf" not in ctype:
            raise MaiambienteError(f"the response is not a PDF ({ctype})")
        return raw


